import {build} from 'esbuild';
import {readFile, writeFile, mkdir, rm, readdir, stat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const options = {bundle: true, platform: 'node', format: 'esm', target: 'node20',
  nodePaths: [path.join(root, 'build/node_modules')], metafile: true};
const scan = await build({...options, entryPoints: ['server.mjs'], write: false});
// Split at these upstream module boundaries; retain readable code for review.
// Anthropic's pre-submission checklist holds non-image files >=256 KiB:
// https://claude.com/docs/plugins/pre-submission-checklist#files-in-the-plugin-folder
const boundaries = [
  'zod/v3/types.js', 'zod/v4/core/util.js', 'zod/v4/core/checks.js',
  'zod/v4/core/schemas.js', 'zod/v4/core/api.js', 'zod/v4/core/to-json-schema.js',
  'zod/v4/mini/schemas.js', 'zod/v4/classic/schemas.js',
  '@modelcontextprotocol/sdk/dist/esm/types.js',
  '@modelcontextprotocol/sdk/dist/esm/shared/protocol.js',
  '@modelcontextprotocol/sdk/dist/esm/server/index.js',
  '@modelcontextprotocol/sdk/dist/esm/server/mcp.js',
  'ajv/dist/compile/codegen/index.js', 'ajv/dist/compile/validate/index.js',
  'ajv/dist/core.js', 'fast-uri/lib/utils.js', 'fast-uri/index.js'
];
const entryPoints = {server: 'server.mjs'};
for (const module of boundaries) {
  const input = Object.keys(scan.metafile.inputs).find(p => p.endsWith('/node_modules/' + module));
  if (!input) throw new Error(`Missing bundle boundary: ${module}`);
  entryPoints['modules/' + module.replace(/\.js$/, '')] = input;
}
await rm('dist', {recursive: true, force: true});
const result = await build({...options, entryPoints, outdir: 'dist', splitting: true,
  outExtension: {'.js': '.mjs'}, legalComments: 'inline',
  banner: {js: 'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);'}});
await mkdir('build', {recursive: true});
await writeFile('build/bundle-inputs.json', JSON.stringify(result.metafile, null, 2) + '\n');

// Preserve the notices for every package whose code is actually in the bundle.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir = path.dirname(path.resolve(input));
  while (dir !== root) {
    try {
      const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
      if (pkg.name && pkg.version) { packages.set(pkg.name, {dir, pkg}); break; }
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const parent = path.dirname(dir);
    if (parent === dir) throw new Error(`No license owner for ${input}`);
    dir = parent;
  }
}
let notices = '# Bundled dependency notices\n\nGenerated by build/bundle.mjs from the pinned build dependencies.\n';
for (const [name, {dir, pkg}] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const files = (await readdir(dir)).filter(n => /^(license|copying)(\.|$)/i.test(n));
  if (!files.length) throw new Error(`Missing license for ${name}`);
  notices += `\n## ${name} ${pkg.version}\n\n`;
  for (const file of files.sort()) notices += (await readFile(path.join(dir, file), 'utf8')) + '\n';
}
await writeFile('THIRD_PARTY_NOTICES.md', notices);
for (const file of Object.keys(result.metafile.outputs)) {
  if ((await stat(file)).size >= 256 * 1024) throw new Error(`Exceeds Anthropic inspection limit: ${file}`);
}
console.log(`Bundled ${packages.size} packages into ${Object.keys(result.metafile.outputs).length} readable files; all under 256 KiB.`);
